// Copy the packages that the page uses from node_modules into vendor/:
// - vendor/clingo-wasm/: the clingo-wasm package (its dist/ folder, unchanged,
//   without the TypeScript types);
// - vendor/fonts/: Open Sans (latin and latin-ext) and the Font Awesome fonts
//   (with their names from Font Awesome 4, as the page uses them), and fonts.css.
//
// To update clingo (or a font):
//   npm install --save-exact clingo-wasm@latest
//   npm run vendor
//   npm test
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkgDir = path.join(root, 'node_modules', 'clingo-wasm');
const src = path.join(pkgDir, 'dist');
const dst = path.join(root, 'vendor', 'clingo-wasm');

if (!fs.existsSync(src)) {
  console.error(`missing ${src}: run "npm install" first`);
  process.exit(1);
}

const version = JSON.parse(fs.readFileSync(path.join(pkgDir, 'package.json'), 'utf8')).version;
fs.rmSync(dst, { recursive: true, force: true });
fs.mkdirSync(dst, { recursive: true });

const lines = [`clingo-wasm ${version}`];
const files = fs.readdirSync(src).filter((f) => !f.endsWith('.d.ts')).sort();
for (const f of files) {
  const data = fs.readFileSync(path.join(src, f));
  fs.writeFileSync(path.join(dst, f), data);
  lines.push(`${crypto.createHash('sha256').update(data).digest('hex')}  ${f}`);
}
fs.copyFileSync(path.join(pkgDir, 'LICENSE'), path.join(dst, 'LICENSE'));
fs.writeFileSync(path.join(dst, 'VERSION'), lines.join('\n') + '\n');
console.log(lines.join('\n'));

// ---- Fonts ------------------------------------------------------------------------

const nm = path.join(root, 'node_modules');
const fonts = path.join(root, 'vendor', 'fonts');
fs.rmSync(fonts, { recursive: true, force: true });
fs.mkdirSync(fonts, { recursive: true });
const pkg_version = (name) => JSON.parse(fs.readFileSync(path.join(nm, name, 'package.json'), 'utf8')).version;
const css = [
  '/* Generated by tools/vendor.mjs. */',
  `/* Open Sans ${pkg_version('@fontsource/open-sans')} (SIL OFL 1.1), from @fontsource/open-sans. */`,
];

// Open Sans: the latin and latin-ext faces of the weights the page uses (woff2 only)
const open_sans = path.join(nm, '@fontsource', 'open-sans');
for (const weight of [400, 600, 700]) {
  const source = fs.readFileSync(path.join(open_sans, `${weight}.css`), 'utf8');
  for (const block of source.match(/\/\* open-sans-latin(-ext)?-\d+-normal \*\/\s*@font-face\s*{[^}]*}/g)) {
    const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(block)[1];
    fs.copyFileSync(path.join(open_sans, 'files', file), path.join(fonts, file));
    css.push(block.replace(/src:[^;]*;/, `src: url('${file}') format('woff2');`));
  }
}
fs.copyFileSync(path.join(open_sans, 'LICENSE'), path.join(fonts, 'LICENSE-open-sans.txt'));

// Font Awesome: all faces under the name 'FontAwesome' (the icons of the tabs, and the
// labels of objects on the board, which games choose by code, e.g. font_f024)
const fa = path.join(nm, '@fortawesome', 'fontawesome-free');
css.push(`/* Font Awesome Free ${pkg_version('@fortawesome/fontawesome-free')} (fonts: SIL OFL 1.1, icons: CC BY 4.0). */`);
const fa_css = fs.readFileSync(path.join(fa, 'css', 'v4-font-face.css'), 'utf8').replace(/\/\*![\s\S]*?\*\/\s*/, '');
for (const m of fa_css.matchAll(/url\("\.\.\/webfonts\/([^"]+)"\)/g)) {
  fs.copyFileSync(path.join(fa, 'webfonts', m[1]), path.join(fonts, m[1]));
}
css.push(fa_css.replace(/\.\.\/webfonts\//g, '').trim());
fs.copyFileSync(path.join(fa, 'LICENSE.txt'), path.join(fonts, 'LICENSE-font-awesome.txt'));

fs.writeFileSync(path.join(fonts, 'fonts.css'), css.join('\n') + '\n');
console.log('fonts: ' + fs.readdirSync(fonts).join(' '));
